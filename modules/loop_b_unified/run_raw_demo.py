"""PyCharm entry. Tools are explicit scripted calls, not a Loop controller."""
from pathlib import Path
import json
import uuid
from provider_setup import create_provider
from review_handoff import make_review_packet, save_review_packet


def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')


def main():
    folder = Path(__file__).resolve().parent / 'raw_outputs' / uuid.uuid4().hex
    task = {'task_id': 'TASK-001', 'run_id': 'RUN-' + uuid.uuid4().hex,
            'customer_id': 'C-DEMO', 'incident_id': 'I-DEMO',
            'event_time': '2026-10-01T00:00:00Z'}
    provider = create_provider(log_path=folder / 'calls.jsonl')
    for source in ('POLICY_DB', 'INCIDENT_DB', 'CRM_CONTRACT_DB', 'MAINTENANCE_CALENDAR', 'TICKET_DB'):
        cursor = None
        for number in range(1, 5):
            result = provider(source, task, cursor)
            dump(folder / (source + '_' + str(number) + '.json'), result)
            print(source, result['tool_status'], 'records=', len(result['records']))
            if result['tool_status'] != 'SUCCESS' or result['pagination_complete']:
                break
            cursor = result['next_page_token']
    # A second explicitly scripted run requests a handoff after PR5 ticket 403.
    blocked_task = {**task, 'run_id': 'RUN-' + uuid.uuid4().hex}
    blocked = create_provider(faults={'TICKET_DB': 'forbidden'}, log_path=folder / 'blocked_calls.jsonl')
    first = blocked('CRM_CONTRACT_DB', blocked_task)
    blocked('CRM_CONTRACT_DB', blocked_task, first['next_page_token'])
    blocked('TICKET_DB', blocked_task)
    snapshot = {k: blocked_task[k] for k in ('task_id', 'run_id')}
    snapshot.update(graph_version=2, answer_version=1, recommendation='undetermined',
                    workflow_status='escalated', stop_reason='ACCESS_DENIED',
                    gaps=[{'gap_type': 'TOOL_BLOCKED', 'target_source': 'TICKET_DB',
                           'affected_claim_ids': ['claim-eligibility'], 'reason': 'PR5 ticket query returned 403'}],
                    scope_declaration='Scripted terminal snapshot for packet demonstration; not generated by Checker.')
    packet = make_review_packet(snapshot, blocked.receipts, [], attempted_rounds=1,
                                questions=['请核查工单权限，并按保留的合同原文继续复核。'])
    save_review_packet(packet, folder)
    print('Outputs:', folder)
    print('Ticket provider: pinned, unmodified PR5 implementation. No private get_ticket used.')


if __name__ == '__main__':
    main()
